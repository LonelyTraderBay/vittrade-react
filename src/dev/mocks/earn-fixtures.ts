export function getTestEarnTransactionsPage(
  domain: EarnDomain,
  cursor?: string,
  limit = 25,
): EarnTransactionPage {
  const transactions = EARN_TRANSACTIONS.filter((transaction) => transaction.domain === domain);
  const offset = cursor ? Number(cursor) || 0 : 0;
  const items = transactions.slice(offset, offset + limit);
  const nextOffset = offset + items.length;
  return {
    items: structuredClone(items),
    ...(nextOffset < transactions.length ? { nextCursor: String(nextOffset) } : {}),
  };
}
